"""Portas: o que o caso de uso precisa do mundo externo, sem saber como é feito.

Os adaptadores (adaptadores/moodle.py, adaptadores/sqlite.py) as implementam; os
testes usam um Moodle em memória.
"""

from datetime import datetime
from typing import Protocol


class Moodle(Protocol):
    """Os Web Services do Moodle que a integração usa."""

    async def usuario_por(self, campo: str, valor: str) -> dict | None: ...
    async def criar_usuario(self, user: dict) -> int: ...
    async def atualizar_usuario(self, user: dict) -> None: ...
    async def categoria_por_idnumber(self, idnumber: str) -> dict | None: ...
    async def criar_categoria(self, nome: str, parent: int, idnumber: str) -> int: ...
    async def curso_por(self, campo: str, valor: str) -> dict | None: ...
    async def criar_curso(self, course: dict) -> int: ...
    async def atualizar_curso(self, course: dict) -> None: ...
    async def inscrever(self, role_id: int, course_id: int, user_id: int) -> None: ...
    async def desinscrever(self, course_id: int, user_id: int) -> None: ...


class EstadoPublicador(Protocol):
    """O que o publicador lembra: ids do Moodle e a versão aplicada de cada entidade."""

    def moodle_id(self, idnumber: str) -> int | None: ...
    def mapear(self, idnumber: str, moodle_id: int) -> None: ...
    def ultimo_ciclo(self, entidade: str) -> datetime | None: ...
    def registrar_ciclo(self, entidade: str, ciclo: datetime) -> None: ...
